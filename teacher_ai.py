def ask_teacher(question):

    question = question.lower()

    if "الذرة" in question:
        return "الذرة هي أصغر جزء من العنصر يحتفظ بخصائصه الكيميائية."

    elif "المول" in question:
        return "المول هو كمية من المادة تحتوي على عدد أفوغادرو من الجسيمات."

    elif "الرابطة الايونية" in question:
        return "الرابطة الأيونية تنتج من انتقال الإلكترونات من ذرة إلى أخرى."

    elif "الرابطة التساهمية" in question:
        return "الرابطة التساهمية تنتج من مشاركة الإلكترونات بين الذرات."

    elif "الجدول الدوري" in question:
        return "الجدول الدوري هو ترتيب للعناصر حسب العدد الذري والخواص الكيميائية."

    else:
        return "حاول صياغة السؤال بشكل أوضح وسيقوم المدرس الإلكتروني بالإجابة."

